// Generates Material 3 colour tokens (light + dark) into src/m3-tokens.css.
// Run with: npm run theme
import { writeFileSync } from 'node:fs'
import {
  argbFromHex, hexFromArgb, Hct, SchemeFidelity, MaterialDynamicColors, Blend, TonalPalette,
} from '@material/material-color-utilities'

const SEED = '#1a73e8'
// One colour per focus style, harmonised toward the seed so they sit in the same scheme.
const FOCUS = ['#d93c6a', '#f29900', '#188038', '#9334e6', '#e8710a']
// Light-mode tone per colour. Amber goes muddy brown at tone 40, so it sits lighter with dark text on it.
const LIGHT_TONE = [40, 70, 40, 40, 50]

const mdc = new MaterialDynamicColors()

function block(dark) {
  const scheme = new SchemeFidelity(Hct.fromInt(argbFromHex(SEED)), dark, 0)
  const lines = []
  for (const c of mdc.allColors) {
    if (!c || c.name.includes('palette_key_color')) continue
    lines.push(`  --md-sys-color-${c.name.replace(/_/g, '-')}: ${hexFromArgb(c.getArgb(scheme))};`)
  }
  FOCUS.forEach((hex, i) => {
    const p = TonalPalette.fromInt(Blend.harmonize(argbFromHex(hex), argbFromHex(SEED)))
    const lt = LIGHT_TONE[i]
    const t = dark ? { c: 80, on: 20, cont: 30, onCont: 90 } : { c: lt, on: lt >= 60 ? 10 : 100, cont: 90, onCont: 10 }
    lines.push(`  --focus-${i + 1}: ${hexFromArgb(p.tone(t.c))};`)
    lines.push(`  --on-focus-${i + 1}: ${hexFromArgb(p.tone(t.on))};`)
    lines.push(`  --focus-${i + 1}-container: ${hexFromArgb(p.tone(t.cont))};`)
    lines.push(`  --on-focus-${i + 1}-container: ${hexFromArgb(p.tone(t.onCont))};`)
  })
  return lines.join('\n')
}

const css = `/* Generated by scripts/gen-theme.mjs from seed ${SEED}. Do not edit by hand. */
:root {
${block(false)}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root {
${block(true).replace(/^/gm, '  ')}
    color-scheme: dark;
  }
}
`
writeFileSync('src/m3-tokens.css', css)
console.log('wrote src/m3-tokens.css')
